// Generates client/src/lib/imageManifest.ts — intrinsic dimensions for every
// image in client/public/Images, plus which ones have a .webp sibling.
// The <Image> component uses this to set width/height (preventing layout shift)
// without every call site having to hardcode them.
import sharp from 'sharp';
import fs from 'node:fs';
import path from 'node:path';

const DIR = 'client/public/Images';
const OUT = 'client/src/lib/imageManifest.ts';

const entries = [];
for (const name of fs.readdirSync(DIR).sort()) {
  if (!/\.(png|jpe?g)$/i.test(name)) continue;
  const original = path.join(DIR, name);
  const meta = await sharp(original).metadata();

  // Prefer WebP only when it actually wins. Flat line-art with alpha (the icon
  // set) compresses better as a palette PNG, so blindly preferring WebP would
  // ship a bigger file.
  const webpPath = path.join(DIR, name.replace(/\.(png|jpe?g)$/i, '.webp'));
  const hasWebp =
    fs.existsSync(webpPath) && fs.statSync(webpPath).size < fs.statSync(original).size;

  entries.push({ src: `/Images/${name}`, w: meta.width, h: meta.height, hasWebp });
}

const body = entries
  .map((e) => `  ${JSON.stringify(e.src)}: { w: ${e.w}, h: ${e.h}, webp: ${e.hasWebp} },`)
  .join('\n');

fs.writeFileSync(
  OUT,
  `// AUTO-GENERATED by scripts/generate-image-manifest.mjs — do not edit by hand.
// Run \`pnpm images\` after adding or replacing files in client/public/Images.

export interface ImageMeta {
  w: number;
  h: number;
  webp: boolean;
}

export const IMAGE_MANIFEST: Record<string, ImageMeta> = {
${body}
};
`,
  'utf-8',
);

console.log(`wrote ${OUT} with ${entries.length} entries`);
console.log(`with webp sibling: ${entries.filter((e) => e.hasWebp).length}`);
